# ═══════════════════════════════════════════════════════════════════════════════
# secrets.sgit.ai — Gen__Search
# Writes data/search-index.json: one entry per page and per rendered document
# (url, twin, title, description, headings, the text), from the markdown twins
# gen_twins wrote. The reader's column searches it offline (tier 0) and the
# chat's search tool reads it (tier 1); nothing leaves the browser for a search.
# Usage: python3 admin/build/gen_search.py [--check]
# ═══════════════════════════════════════════════════════════════════════════════

import json
import re
import sys

from chrome import ROOT, Chrome
from pages  import Site__Pages


INDEX_FILE   = ROOT / 'data' / 'search-index.json'
TEXT_LIMIT   = 6000                                                                # characters of text kept per entry; the chat's open_page reads the whole twin
RE_HEADING   = re.compile(r'^#{1,3}\s+(.+?)\s*$', re.M)
RE_MARKUP    = re.compile(r'[`*_>#|]|\[([^\]]*)\]\([^)]*\)|<[^>]+>')
RE_SPACE     = re.compile(r'[ \t]+')
RE_BLANKS    = re.compile(r'\n{2,}')


class Gen__Search:

    def __init__(self, check=False):
        self.check  = check
        self.chrome = Chrome()
        self.pages  = Site__Pages()

    def clean(self, markdown):
        body = markdown.split('\n---\n', 1)[1] if '\n---\n' in markdown else markdown   # after the twin header
        body = body.rsplit('\n---\n', 1)[0] if '\n---\n' in body else body             # before the twin footer
        text = RE_MARKUP.sub(lambda m: m.group(1) or '', body)
        text = RE_BLANKS.sub('\n', RE_SPACE.sub(' ', text)).strip()
        return text[:TEXT_LIMIT]

    def entry(self, page):
        twin = self.chrome.twin_path(page['url'])
        md   = (ROOT / twin.lstrip('/')).read_text(encoding='utf-8') if (ROOT / twin.lstrip('/')).exists() else ''
        return {'url'         : page['url'],
                'twin'        : twin,
                'title'       : page['title'].split(' — ')[0],
                'description' : page['description'],
                'headings'    : RE_HEADING.findall(md)[1:],                           # the first heading is the title
                'text'        : self.clean(md)}

    def entries(self):
        found = []
        for path in self.pages.html_files():
            page = self.pages.meta(path)
            if page['url'] == '/404.html':
                continue
            if page['source']:                                                       # a rendered document: its markdown is the twin
                page = dict(page)
            found.append(self.entry(page))
        return sorted(found, key=lambda e: e['url'])

    def render(self):
        data = {'version' : 1,
                'site'    : self.chrome.host,
                'siteVersion' : self.chrome.version,
                '_comment': 'Generated by admin/build/gen_search.py from the markdown twins; searched in the browser by the reader\'s column. Do not edit.',
                'entries' : self.entries()}
        return json.dumps(data, indent=1, ensure_ascii=False) + '\n'

    def run(self):
        return self.pages.write_if_changed(INDEX_FILE, self.render(), self.check)


if __name__ == '__main__':
    check   = '--check' in sys.argv
    changed = Gen__Search(check=check).run()
    if check and changed:
        print('gen_search --check: data/search-index.json is out of date; run python3 admin/build/gen_search.py')
        sys.exit(1)
    print(f'gen_search: data/search-index.json {"stale" if changed else "fresh"}' if check else f'gen_search: data/search-index.json {"updated" if changed else "unchanged"}')
